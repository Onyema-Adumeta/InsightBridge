"use client";

import { useState, useEffect } from 'react';
import { BookOpen, Search, TrendingUp, User, BarChart3, Plus, Edit, Trash2, ChevronRight, Lightbulb, X } from 'lucide-react';

const API_URL = process.env.NEXT_PUBLIC_API_URL || 'http://127.0.0.1:8000';

interface FinanceTerm {
  id: string;
  term: string;
  category: string;
  definition: string;
  example: string;
  bestPractice: string;
}

interface LiteracyTerm {
  term: string;
  definition: string;
  example: string;
  formula?: string;
}

export default function LearnFinancePage() {
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState('all');
  const [showAddForm, setShowAddForm] = useState(false);
  const [terms, setTerms] = useState<FinanceTerm[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [selectedLiteracyTerm, setSelectedLiteracyTerm] = useState<LiteracyTerm | null>(null);
  
  const [newTerm, setNewTerm] = useState({
    term: '',
    category: 'revenue',
    definition: '',
    example: '',
    bestPractice: ''
  });

  const categories = [
    { id: 'all', name: 'All Categories', icon: BookOpen },
    { id: 'revenue', name: 'Revenue Metrics', icon: TrendingUp },
    { id: 'customer', name: 'Customer Metrics', icon: User },
    { id: 'profitability', name: 'Profitability', icon: BarChart3 }
  ];

  // Quick reference financial terms
  const literacyTerms: LiteracyTerm[] = [
    {
      term: "Gross Margin",
      definition: "The percentage of revenue remaining after subtracting the cost of goods sold. Shows how efficiently a company produces its products.",
      example: "If revenue is $100K and COGS is $40K, gross margin = ($100K - $40K) / $100K = 60%",
      formula: "(Revenue - COGS) / Revenue × 100"
    },
    {
      term: "Current Ratio",
      definition: "Measures a company's ability to pay short-term obligations. A ratio above 1.0 indicates good liquidity.",
      example: "If current assets are $200K and current liabilities are $100K, current ratio = 2.0",
      formula: "Current Assets / Current Liabilities"
    },
    {
      term: "Free Cash Flow (FCF)",
      definition: "Cash generated by operations minus capital expenditures. Shows cash available for expansion, dividends, or debt repayment.",
      example: "If operating cash flow is $500K and CapEx is $100K, FCF = $400K",
      formula: "Operating Cash Flow - Capital Expenditures"
    },
    {
      term: "Operating Margin",
      definition: "Operating income as a percentage of revenue. Indicates how much profit a company makes from operations before taxes and interest.",
      example: "If revenue is $1M and operating income is $150K, operating margin = 15%",
      formula: "Operating Income / Revenue × 100"
    },
    {
      term: "EBITDA",
      definition: "Earnings Before Interest, Taxes, Depreciation, and Amortization. Used to analyze operating profitability.",
      example: "Net income $100K + Interest $20K + Taxes $30K + D&A $50K = EBITDA $200K",
      formula: "Net Income + Interest + Taxes + Depreciation + Amortization"
    },
    {
      term: "Debt-to-Equity Ratio",
      definition: "Compares total debt to shareholder equity. Higher ratios indicate more leverage and financial risk.",
      example: "If total debt is $300K and equity is $500K, ratio = 0.6",
      formula: "Total Debt / Total Equity"
    }
  ];

  useEffect(() => {
    fetchTerms();
  }, [selectedCategory, searchTerm]);

  const fetchTerms = async () => {
    try {
      setIsLoading(true);
      const params = new URLSearchParams();
      if (selectedCategory !== 'all') params.append('category', selectedCategory);
      if (searchTerm) params.append('search', searchTerm);

      const response = await fetch(`${API_URL}/api/learn-finance/terms?${params}`);
      const data = await response.json();
      setTerms(data.terms || []);
    } catch (error) {
      console.error('Error fetching terms:', error);
    } finally {
      setIsLoading(false);
    }
  };

  const handleAddTerm = async () => {
    if (!newTerm.term || !newTerm.definition) return;

    try {
      const response = await fetch(`${API_URL}/api/learn-finance/terms`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(newTerm)
      });

      if (response.ok) {
        setNewTerm({
          term: '',
          category: 'revenue',
          definition: '',
          example: '',
          bestPractice: ''
        });
        setShowAddForm(false);
        fetchTerms();
      }
    } catch (error) {
      console.error('Error adding term:', error);
    }
  };

  const handleDeleteTerm = async (termId: string) => {
    if (!confirm('Are you sure you want to delete this term?')) return;

    try {
      const response = await fetch(`${API_URL}/api/learn-finance/terms/${termId}`, {
        method: 'DELETE'
      });

      if (response.ok) {
        fetchTerms();
      }
    } catch (error) {
      console.error('Error deleting term:', error);
    }
  };

  return (
    <div className="ml-64 min-h-screen bg-slate-50">
      {/* Header */}
      <div className="bg-white border-b border-slate-200 sticky top-0 z-10">
        <div className="max-w-7xl mx-auto px-6 py-4">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 bg-indigo-600 rounded-lg flex items-center justify-center">
                <BookOpen className="w-5 h-5 text-white" />
              </div>
              <div>
                <h1 className="text-2xl font-bold text-slate-900">Learn Finance</h1>
                <p className="text-sm text-slate-600">Financial metrics knowledge base for your team</p>
              </div>
            </div>
            <div className="flex items-center gap-3">
              <div className="relative w-80">
                <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 text-slate-400 w-4 h-4" />
                <input
                  type="text"
                  placeholder="Search terms, definitions..."
                  value={searchTerm}
                  onChange={(e) => setSearchTerm(e.target.value)}
                  className="w-full pl-10 pr-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent"
                />
              </div>
              <button
                onClick={() => setShowAddForm(!showAddForm)}
                className="px-4 py-2 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 flex items-center gap-2 transition"
              >
                <Plus className="w-4 h-4" />
                Add Term
              </button>
            </div>
          </div>
        </div>
      </div>

      {/* Main Content */}
      <div className="max-w-7xl mx-auto px-6 py-8">
        {/* Financial Literacy Corner - NEW */}
        <div className="mb-8 bg-gradient-to-br from-indigo-50 via-blue-50 to-purple-50 rounded-xl border border-indigo-200 p-6">
          <div className="flex items-center gap-3 mb-4">
            <div className="w-10 h-10 bg-gradient-to-br from-indigo-500 to-purple-600 rounded-lg flex items-center justify-center">
              <Lightbulb className="w-5 h-5 text-white" />
            </div>
            <div>
              <h2 className="text-xl font-bold text-slate-900">Financial Literacy Corner</h2>
              <p className="text-sm text-slate-600">Click any term below to learn more about key financial metrics</p>
            </div>
          </div>
          
          <div className="grid grid-cols-2 md:grid-cols-3 gap-3">
            {literacyTerms.map((term, idx) => (
              <button
                key={idx}
                onClick={() => setSelectedLiteracyTerm(term)}
                className="flex items-center justify-between p-3 bg-white rounded-lg border border-slate-200 hover:border-indigo-400 hover:shadow-md transition-all group"
              >
                <span className="text-sm font-semibold text-slate-900 group-hover:text-indigo-600">
                  {term.term}
                </span>
                <ChevronRight className="w-4 h-4 text-slate-400 group-hover:text-indigo-600" />
              </button>
            ))}
          </div>
        </div>

        <div className="grid grid-cols-12 gap-6">
          {/* Sidebar Categories */}
          <div className="col-span-3">
            <div className="bg-white rounded-xl border border-slate-200 shadow-sm p-4 sticky top-24">
              <h3 className="text-sm font-semibold text-slate-900 mb-3 px-2">Categories</h3>
              <div className="space-y-1">
                {categories.map(category => {
                  const Icon = category.icon;
                  return (
                    <button
                      key={category.id}
                      onClick={() => setSelectedCategory(category.id)}
                      className={`w-full flex items-center gap-3 px-3 py-2.5 rounded-lg transition-all ${
                        selectedCategory === category.id
                          ? 'bg-indigo-50 text-indigo-700 font-medium'
                          : 'text-slate-700 hover:bg-slate-50'
                      }`}
                    >
                      <Icon className="w-4 h-4" />
                      <span className="text-sm">{category.name}</span>
                    </button>
                  );
                })}
              </div>
            </div>
          </div>

          {/* Content Area */}
          <div className="col-span-9 space-y-6">
            {/* Add Term Form */}
            {showAddForm && (
              <div className="bg-white rounded-xl border border-slate-200 shadow-sm p-6">
                <h3 className="text-lg font-semibold text-slate-900 mb-4">Add New Financial Term</h3>
                <div className="space-y-4">
                  <div className="grid grid-cols-2 gap-4">
                    <div>
                      <label className="block text-sm font-medium text-slate-700 mb-2">
                        Term Name *
                      </label>
                      <input
                        type="text"
                        value={newTerm.term}
                        onChange={(e) => setNewTerm({...newTerm, term: e.target.value})}
                        placeholder="e.g., MRR, CAC, Churn Rate"
                        className="w-full px-3 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent"
                      />
                    </div>
                    <div>
                      <label className="block text-sm font-medium text-slate-700 mb-2">
                        Category *
                      </label>
                      <select
                        value={newTerm.category}
                        onChange={(e) => setNewTerm({...newTerm, category: e.target.value})}
                        className="w-full px-3 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent"
                      >
                        <option value="revenue">Revenue Metrics</option>
                        <option value="customer">Customer Metrics</option>
                        <option value="profitability">Profitability</option>
                      </select>
                    </div>
                  </div>

                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-2">
                      Definition *
                    </label>
                    <textarea
                      value={newTerm.definition}
                      onChange={(e) => setNewTerm({...newTerm, definition: e.target.value})}
                      placeholder="Clear, concise definition of the term"
                      rows={3}
                      className="w-full px-3 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent resize-none"
                    />
                  </div>

                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-2">
                      Example
                    </label>
                    <textarea
                      value={newTerm.example}
                      onChange={(e) => setNewTerm({...newTerm, example: e.target.value})}
                      placeholder="Practical example showing how to calculate or use this metric"
                      rows={2}
                      className="w-full px-3 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent resize-none"
                    />
                  </div>

                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-2">
                      Best Practice
                    </label>
                    <textarea
                      value={newTerm.bestPractice}
                      onChange={(e) => setNewTerm({...newTerm, bestPractice: e.target.value})}
                      placeholder="Best practices, benchmarks, or tips for this metric"
                      rows={2}
                      className="w-full px-3 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-transparent resize-none"
                    />
                  </div>

                  <div className="flex justify-end gap-3 pt-4 border-t border-slate-200">
                    <button
                      onClick={() => setShowAddForm(false)}
                      className="px-4 py-2 text-slate-700 hover:bg-slate-100 rounded-lg transition"
                    >
                      Cancel
                    </button>
                    <button
                      onClick={handleAddTerm}
                      disabled={!newTerm.term || !newTerm.definition}
                      className="px-4 py-2 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 disabled:bg-slate-300 disabled:cursor-not-allowed transition"
                    >
                      Add Term
                    </button>
                  </div>
                </div>
              </div>
            )}

            {/* Terms List */}
            {isLoading ? (
              <div className="bg-white rounded-xl border border-slate-200 shadow-sm p-12 text-center">
                <p className="text-slate-500">Loading terms...</p>
              </div>
            ) : terms.length > 0 ? (
              <div className="space-y-4">
                {terms.map(term => (
                  <div key={term.id} className="bg-white rounded-xl border border-slate-200 shadow-sm p-6 hover:shadow-md transition">
                    <div className="flex items-start justify-between mb-3">
                      <div className="flex-1">
                        <div className="flex items-center gap-3 mb-2">
                          <h3 className="text-xl font-semibold text-slate-900">{term.term}</h3>
                          <span className="px-2.5 py-0.5 bg-indigo-100 text-indigo-700 text-xs font-medium rounded-full">
                            {categories.find(c => c.id === term.category)?.name}
                          </span>
                        </div>
                        <p className="text-slate-700 mb-4">{term.definition}</p>
                        
                        {term.example && (
                          <div className="mb-3">
                            <h4 className="text-sm font-semibold text-slate-900 mb-1">Example:</h4>
                            <p className="text-sm text-slate-600 bg-slate-50 p-3 rounded-lg">{term.example}</p>
                          </div>
                        )}
                        
                        {term.bestPractice && (
                          <div>
                            <h4 className="text-sm font-semibold text-slate-900 mb-1">Best Practice:</h4>
                            <p className="text-sm text-slate-600 bg-indigo-50 p-3 rounded-lg">{term.bestPractice}</p>
                          </div>
                        )}
                      </div>
                      
                      <div className="flex items-center gap-2 ml-4">
                        <button className="p-2 text-slate-400 hover:text-indigo-600 hover:bg-indigo-50 rounded-lg transition">
                          <Edit className="w-4 h-4" />
                        </button>
                        <button 
                          onClick={() => handleDeleteTerm(term.id)}
                          className="p-2 text-slate-400 hover:text-red-600 hover:bg-red-50 rounded-lg transition"
                        >
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <div className="bg-white rounded-xl border border-slate-200 shadow-sm p-12 text-center">
                <BookOpen className="w-16 h-16 mx-auto mb-4 text-slate-300" />
                <h3 className="text-lg font-semibold text-slate-900 mb-2">No terms found</h3>
                <p className="text-slate-600 mb-6">
                  {searchTerm 
                    ? "No terms match your search. Try different keywords."
                    : "Start building your financial knowledge base by adding terms."}
                </p>
                <button
                  onClick={() => setShowAddForm(true)}
                  className="px-4 py-2 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 inline-flex items-center gap-2"
                >
                  <Plus className="w-4 h-4" />
                  Add Your First Term
                </button>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Modal for Literacy Term Details */}
      {selectedLiteracyTerm && (
        <div className="fixed inset-0 bg-black/50 flex items-center justify-center z-50 p-4">
          <div className="bg-white rounded-2xl max-w-2xl w-full p-8 relative">
            <button
              onClick={() => setSelectedLiteracyTerm(null)}
              className="absolute top-4 right-4 p-2 hover:bg-slate-100 rounded-lg transition"
            >
              <X className="w-5 h-5 text-slate-400" />
            </button>
            
            <div className="mb-6">
              <h2 className="text-3xl font-bold text-slate-900 mb-2">{selectedLiteracyTerm.term}</h2>
              <p className="text-slate-700 leading-relaxed">{selectedLiteracyTerm.definition}</p>
            </div>

            {selectedLiteracyTerm.formula && (
              <div className="mb-6 p-4 bg-indigo-50 border border-indigo-200 rounded-lg">
                <h3 className="text-sm font-semibold text-indigo-900 mb-2">Formula:</h3>
                <code className="text-indigo-700 font-mono">{selectedLiteracyTerm.formula}</code>
              </div>
            )}

            <div className="mb-6 p-4 bg-slate-50 rounded-lg">
              <h3 className="text-sm font-semibold text-slate-900 mb-2">Example:</h3>
              <p className="text-sm text-slate-700">{selectedLiteracyTerm.example}</p>
            </div>

            <button
              onClick={() => setSelectedLiteracyTerm(null)}
              className="w-full px-4 py-3 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 font-semibold transition"
            >
              Got it!
            </button>
          </div>
        </div>
      )}
    </div>
  );
}