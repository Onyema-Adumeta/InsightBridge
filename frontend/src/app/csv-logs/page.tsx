"use client";

export const dynamic = 'force-dynamic';

import { useEffect, useState } from "react";
import Link from "next/link";
import { Info } from "lucide-react";
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from "@/components/ui/tooltip";

interface CsvLog {
  filename: string;
  timestamp: string;
  total_txns: number;
  total_amount: number;
  kpis?: Record<string, number>;
  ai_classification?: string[];
}

const kpiDefinitions: Record<string, string> = {
  net_income: "Net income is the total profit of a company after all expenses and taxes.",
  cash_flow_ops: "Cash flow from operations represents the cash generated by regular business activities.",
  revenue: "Revenue is the total income generated from sales of goods or services.",
  ebitda: "EBITDA stands for Earnings Before Interest, Taxes, Depreciation, and Amortization."
};

export default function CsvLogsPage() {
  const [logs, setLogs] = useState<CsvLog[]>([]);
  const [error, setError] = useState("");

  useEffect(() => {
    const fetchLogs = async () => {
      try {
        const res = await fetch("/api/csv_summary_logs");
        if (!res.ok) throw new Error("Failed to load CSV logs");
        const data = await res.json();
        setLogs(data);
      } catch (err: any) {
        setError(err.message);
      }
    };

    fetchLogs();
  }, []);

  return (
    <TooltipProvider>
      <div className="p-6">
        <h1 className="text-xl font-semibold mb-4">📊 CSV Upload History</h1>
        {error ? (
          <p className="text-red-500">❌ {error}</p>
        ) : logs.length === 0 ? (
          <p className="text-gray-400">No results found.</p>
        ) : (
          <div className="space-y-4">
            {logs.map((log, idx) => (
              <div
                key={idx}
                className="border border-gray-600 rounded-lg p-4 bg-gray-800 shadow hover:shadow-lg transition"
              >
                <div className="flex justify-between items-center">
                  <div>
                    <h2 className="text-sm font-bold text-white">
                      {log.filename}
                    </h2>
                    <p className="text-xs text-gray-400 mb-2">{log.timestamp}</p>
                  </div>
                  <Link
                    href={`/csv-logs/${encodeURIComponent(log.filename)}`}
                    className="text-blue-400 text-sm hover:underline"
                  >
                    View Details →
                  </Link>
                </div>
                <p className="text-sm text-gray-300 mt-1">
                  🧾 {log.total_txns} transactions, 💰 ${log.total_amount.toFixed(2)}
                </p>
                {log.kpis && (
                  <div className="text-xs text-gray-300 mt-2 space-y-1">
                    {Object.entries(log.kpis).map(([key, value]) => (
                      <div key={key} className="flex items-center gap-1">
                        <strong>{key.replace(/_/g, " ")}:</strong> {value.toLocaleString()}
                        {kpiDefinitions[key] && (
                          <Tooltip>
                            <TooltipTrigger asChild>
                              <Info className="w-3 h-3 text-blue-300 cursor-help" />
                            </TooltipTrigger>
                            <TooltipContent className="max-w-sm text-xs text-white bg-gray-900 border border-gray-600">
                              {kpiDefinitions[key]}
                            </TooltipContent>
                          </Tooltip>
                        )}
                      </div>
                    ))}
                  </div>
                )}
                {log.ai_classification && log.ai_classification.length > 0 && (
                  <div className="mt-2 flex flex-wrap gap-2">
                    {log.ai_classification.map((tag, i) => (
                      <span
                        key={i}
                        className="text-xs bg-purple-900 text-purple-200 px-2 py-0.5 rounded-full"
                      >
                        #{tag}
                      </span>
                    ))}
                  </div>
                )}
              </div>
            ))}
          </div>
        )}
      </div>
    </TooltipProvider>
  );
}
